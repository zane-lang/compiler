(* Report every place an OCaml file nests deeper than the limit.

   Depth is counted on the parsed tree, not on indentation: each `match`,
   `function`/`fun`, `try`, `if`, `while` and `for` that encloses an expression
   is one level. Three shapes count less than their syntax suggests, because
   counting them would punish the code the limit asks for:

   - A function bound by `let`, at top level or locally, costs nothing; its
     body still counts. Naming an inner step is how a deep function is brought
     back under the limit, so the name must not cost a level. A
     `let f = function | ...` still counts its cases, as the `match` they are.
   - An anonymous `fun x -> match x with` is one level, not two.
   - An `else if` chain is one level, however many links it has.

   A site is the expression where the depth first goes past the limit. Each is
   reported once, as a GitHub annotation naming the chain of levels down to it;
   what nests further inside it is the same problem and is not reported again.
   The tool exits 1 when it reports anything.

   Generated files are skipped by the same rule as `.github/scripts/file-sizes`:
   a first line that says "Generated by" or "Written by". *)

open Parsetree

let limit = 5

let kind e =
  match e.pexp_desc with
  | Pexp_match _ -> Some "match"
  | Pexp_function (_, _, Pfunction_cases _) -> Some "function"
  | Pexp_function _ -> Some "fun"
  | Pexp_try _ -> Some "try"
  | Pexp_ifthenelse _ -> Some "if"
  | Pexp_while _ -> Some "while"
  | Pexp_for _ -> Some "for"
  | _ -> None

(* A [free] expression is a function bound by `let` or the `if` after an
   `else`, whose own level is already paid for. A `function | ...` is free of
   its `fun` but not of its cases. *)
let level ~free e =
  match e.pexp_desc with
  | Pexp_function (_, _, Pfunction_cases _) -> kind e
  | _ when free -> None
  | _ -> kind e

let rec is_function e =
  match e.pexp_desc with
  | Pexp_function _ -> true
  | Pexp_constraint (e, _) | Pexp_newtype (_, e) -> is_function e
  | _ -> false

type site = { line : int; chain : string list }

let sites = ref []

(* [chain] holds the levels enclosing [e], innermost first. *)
let rec walk ?(free = false) chain e =
  match level ~free e with
  | Some kind when List.length chain >= limit ->
      sites := { line = e.pexp_loc.loc_start.pos_lnum; chain = List.rev (kind :: chain) } :: !sites
  | Some kind -> children ~free (kind :: chain) e
  | None -> children ~free chain e

and children ~free chain e =
  match e.pexp_desc with
  | (Pexp_constraint (inner, _) | Pexp_newtype (_, inner)) when free -> walk ~free chain inner
  | Pexp_function (params, _, Pfunction_body { pexp_desc = Pexp_match (scrutinee, cases); _ })
    when not free ->
      List.iter (default_argument chain) params;
      walk chain scrutinee;
      List.iter (case chain) cases
  | Pexp_ifthenelse (condition, then_, Some ({ pexp_desc = Pexp_ifthenelse _; _ } as else_)) ->
      walk chain condition;
      walk chain then_;
      walk ~free:true chain else_
  | _ -> Ast_iterator.default_iterator.expr (iterator chain) e

and default_argument chain param =
  match param.pparam_desc with
  | Pparam_val (_, Some default, _) -> walk chain default
  | Pparam_val (_, None, _) | Pparam_newtype _ -> ()

and case chain c =
  Option.iter (walk chain) c.pc_guard;
  walk chain c.pc_rhs

(* Every binding reached through the iterator, a `let module`'s included, is
   measured the same way as a local `let`. *)
and iterator chain =
  {
    Ast_iterator.default_iterator with
    expr = (fun _ e -> walk chain e);
    value_binding = (fun _ vb -> walk ~free:(is_function vb.pvb_expr) chain vb.pvb_expr);
  }

let contains ~sub s =
  let n = String.length sub in
  let rec from i = i + n <= String.length s && (String.sub s i n = sub || from (i + 1)) in
  from 0

let generated file =
  match In_channel.with_open_text file In_channel.input_line with
  | Some line -> contains ~sub:"Generated by" line || contains ~sub:"Written by" line
  | None -> false

let check file =
  sites := [];
  let it = iterator [] in
  it.structure it (Pparse.parse_implementation ~tool_name:"nesting" file);
  List.rev !sites

let annotate file { line; chain } =
  Printf.printf
    "::error file=%s,line=%d::%s:%d nests %d deep (%s), past the limit of %d; name the inner steps \
     as functions\n"
    file line file line (List.length chain) (String.concat " > " chain) limit

let () =
  let files = List.tl (Array.to_list Sys.argv) in
  let failed = ref false in
  List.iter
    (fun file ->
      if not (generated file) then begin
        let sites = check file in
        List.iter (annotate file) sites;
        if sites <> [] then failed := true
      end)
    files;
  exit (if !failed then 1 else 0)
