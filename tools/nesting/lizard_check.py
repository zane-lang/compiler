#!/usr/bin/env python3
"""Report every C or Python function that nests as deep as the limit or deeper.

The OCaml sources have their own count, `nesting.ml` beside this file; this is
the same rule for the C runtime and the Python tooling, counted by lizard
(https://github.com/terryyin/lizard), pinned in pixi.toml. Its "nested
structures" extension measures, per function, the deepest chain of `if`,
`for`, `while`, `do`, `switch`, `try` and `with` (and Python's `match`), on
the token stream rather than on indentation. As in the OCaml count:

- A function's own body is level zero, and a function defined inside another
  is measured on its own, so naming an inner step flattens the outer one.
- A Python `elif` chain is one level, and so is a `case` under its `match`.

One difference: lizard charges each C `else if` as a level of its own, so a
long chain in C nests as deep as it is long. Write such a chain as a `switch`
or as early returns.

Five levels is the limit. A function that goes past it is an error; one that
reaches it is a warning, as in the OCaml count. lizard gives the depth of a
function, not where in it the depth is reached, so each report names the
function at its first line. Each is a GitHub annotation, and the tool exits 1
when it reports an error.

A file is measured as C or Python by its extension, or as Python by a
`python` shebang; any other file named is ignored. Generated files are skipped
by the same rule as `.github/scripts/file-sizes`: a first line that says
"Generated by" or "Written by".
"""

from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path

import lizard

LIMIT = 5


@dataclass(frozen=True)
class Site:
    error: bool
    line: int
    name: str
    depth: int


def language_name(path: str, first_line: str) -> str | None:
    """The name lizard should read [path] under, which picks its language."""
    if path.endswith((".c", ".h", ".py")):
        return path
    if first_line.startswith("#!") and "python" in first_line:
        return path + ".py"
    return None


def generated(first_line: str) -> bool:
    return "Generated by" in first_line or "Written by" in first_line


def check_source(name: str, code: str) -> list[Site]:
    analyzer = lizard.FileAnalyzer(lizard.get_extensions(["NS"]))
    functions = analyzer.analyze_source_code(name, code).function_list
    return [
        Site(f.max_nested_structures > LIMIT, f.start_line, f.name, f.max_nested_structures)
        for f in functions
        if f.max_nested_structures >= LIMIT
    ]


def first_line_of(path: str) -> str:
    """The first line, read as bytes so a binary file is no error."""
    with open(path, "rb") as f:
        return f.readline().decode("utf-8", errors="replace").rstrip("\r\n")


def check(path: str) -> list[Site]:
    # Only a file this measures is read whole, so one that is not C or Python
    # need not be text.
    name = language_name(path, first_line_of(path))
    if name is None:
        return []
    code = Path(path).read_text(encoding="utf-8")
    if generated(code.split("\n", 1)[0]):
        return []
    return sorted(check_source(name, code), key=lambda site: site.line)


def annotate(path: str, site: Site) -> str:
    where = f"{path}:{site.line}"
    if site.error:
        return (
            f"::error file={path},line={site.line}::{where} `{site.name}` nests {site.depth} "
            f"deep, past the limit of {LIMIT}; name the inner steps as functions"
        )
    return (
        f"::warning file={path},line={site.line}::{where} `{site.name}` nests {site.depth} "
        "deep, at the limit; it is allowed for an outlier, but three levels is the aim, "
        "so name the inner steps as functions where that reads better"
    )


def main(paths: list[str]) -> int:
    failed = False
    for path in paths:
        for site in check(path):
            print(annotate(path, site))
            failed = failed or site.error
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
